import numpy as np

# 정사각 crop 이 16:9 원본의 전체 높이를 쓴다는 기하에서 나오는 값. **9/8 까지 쓰던 어림값이다.**
# 남겨 둔 이유 — tools/aruco_offline_check.py 가 '보정 전/어림/실측'을 나란히 대조할 때 쓴다.
FX_SCALE_CROP_16_9 = 16.0 / 9.0

# 9/9 체커보드 실측 (tools/checker_calib.py) — **출발점이지 확정 근거가 아니다.**
#   robot3  566.65 × 1.83 ≈ 1038        robot8  566.01 × 1.83 ≈ 1038
# 두 대가 1 px 안에서 같게 나오지만, 같은 사진에서 20장씩 다시 풀면 13~28 % 폭으로 흔들린다.
# 우연히 가까운 것이므로 이것을 근거로 삼지 않는다 (윗글 참조). **확정은 9/10 줄자 대조다** —
# robot3 5점 1.7 cm 안, robot8 운용 구간(0.9~1.5 m) +0.7~+3.2 cm. 로봇별로 나눌 이유가 없어 공용.
FX_SCALE_MEASURED = 1.8336

PARAM = 'camera_fx_scale'


def read_fx_scale(node):
    """`camera_fx_scale` 을 선언·검증해 돌려준다. 두 노드가 같은 이름·같은 기본값을 쓰도록.

    기본값이 곧 정답이어야 한다 — `ros2 run` 으로 노드만 띄우면 yaml 이 안 붙기 때문이다.
    (robot.launch.py 는 perception.yaml 을 넘기므로 실기에서는 yaml 값이 이긴다.)
    """
    node.declare_parameter(PARAM, FX_SCALE_MEASURED)
    s = float(node.get_parameter(PARAM).value)
    if not 0.1 <= s <= 10.0:
        # 0 이나 음수가 조용히 먹으면 거리가 통째로 0 이 되고 원인을 찾는 데 하루가 든다
        node.get_logger().error(f'{PARAM}={s} 는 범위 밖 — 보정 없이(1.0) 진행한다')
        return 1.0
    return s


def corrected_K(msg, fx_scale):
    """CameraInfo → 보정한 3×3 카메라 행렬. fx_scale=1.0 이면 원본 그대로."""
    K = np.array(msg.k, dtype=np.float64).reshape(3, 3)
    K[0, 0] *= fx_scale
    K[1, 1] *= fx_scale
    return K
